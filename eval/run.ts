/**
 * OCD-Eval: measures how well Dhriti understands what users say.
 *
 * Compares three systems on the multilingual OCD-Eval set:
 *   1. Rules     - the offline lexicon classifier (evaluated on the full set)
 *   2. NB model  - multinomial Naive Bayes on word uni+bigrams (stratified 5-fold CV)
 *   3. Hybrid    - rules + model, as used in the app (stratified 5-fold CV)
 *
 * Release gate: self-harm recall must be >= 0.99 for the shipped (hybrid) system.
 * Exits with code 1 when the gate fails, so it can run in CI.
 *
 * Also trains the final Naive Bayes model on all data and exports it for the app.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EVAL_SET } from './dataset';
import { HOLDOUT_SET } from './holdout';
import { classify } from '../shared/nlp/classifier';
import { classifyHybrid } from '../shared/nlp/ensemble';
import { tokens } from '../shared/nlp/normalize';
import { classificationReport, confusionMatrix, macroF1, nbPredictProba, stratifiedKFold, trainNaiveBayes } from '../shared/ml/core';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CLASSES = ['SELF_HARM', 'EMERGENCY', 'MEDICAL', 'PANIC', 'REASSURANCE', 'URGE', 'DIARY', 'UNCLEAR'];
const GATE = 0.99;

const texts = EVAL_SET.map((e) => e.text);
const labels = EVAL_SET.map((e) => e.label as string);
const docs = texts.map((t) => tokens(t));

// 1. Rules on the full set
const rulesPred = texts.map((t) => classify(t).intent as string);

// 2 + 3. Cross-validated model and hybrid
const folds = stratifiedKFold(labels, 5, 42);
const nbPred = new Array<string>(labels.length);
const hybridPred = new Array<string>(labels.length);
for (const test of folds) {
  const testSet = new Set(test);
  const trainIdx = labels.map((_, i) => i).filter((i) => !testSet.has(i));
  const nb = trainNaiveBayes(trainIdx.map((i) => docs[i]), trainIdx.map((i) => labels[i]));
  for (const i of test) {
    const p = nbPredictProba(nb, docs[i]);
    nbPred[i] = Object.entries(p).sort((a, b) => b[1] - a[1])[0][0];
    hybridPred[i] = classifyHybrid(texts[i], nb).intent;
  }
}

function summarise(name: string, pred: string[]) {
  const rep = classificationReport(labels, pred, CLASSES);
  const acc = labels.filter((l, i) => l === pred[i]).length / labels.length;
  return { name, acc, macroF1: macroF1(rep), rep, cm: confusionMatrix(labels, pred, CLASSES) };
}

const systems = [summarise('Rules (full set)', rulesPred), summarise('Naive Bayes (5-fold CV)', nbPred), summarise('Hybrid, shipped (5-fold CV)', hybridPred)];
const hybrid = systems[2];
const selfHarmRecall = hybrid.rep.SELF_HARM.recall;
const gatePassed = selfHarmRecall >= GATE;

const byLang = [...new Set(EVAL_SET.map((e) => e.lang))].map((lang) => {
  const idx = EVAL_SET.map((e, i) => (e.lang === lang ? i : -1)).filter((i) => i >= 0);
  const acc = idx.filter((i) => hybridPred[i] === labels[i]).length / idx.length;
  return { lang, n: idx.length, acc };
});

const misses = EVAL_SET.map((e, i) => ({ ...e, pred: hybridPred[i] })).filter((e) => e.pred !== e.label);

// Final model on all data, exported for the app.
const finalNb = trainNaiveBayes(docs, labels);

// Held-out generalisation estimate (never used for tuning).
const hoLabels = HOLDOUT_SET.map((h) => h.label as string);
const hoPred = HOLDOUT_SET.map((h) => classifyHybrid(h.text, finalNb).intent as string);
const hoRep = classificationReport(hoLabels, hoPred, CLASSES);
const hoAcc = hoLabels.filter((l, i) => l === hoPred[i]).length / hoLabels.length;
const hoHarmIdx = HOLDOUT_SET.map((h, i) => (h.label === 'SELF_HARM' ? i : -1)).filter((i) => i >= 0);
const hoSafetyCatch = hoHarmIdx.filter((i) => { const c = classifyHybrid(HOLDOUT_SET[i].text, finalNb); return c.intent === 'SELF_HARM' || c.riskCheck; }).length / Math.max(hoHarmIdx.length, 1);
const hoMisses = HOLDOUT_SET.map((h, i) => ({ ...h, pred: hoPred[i] })).filter((h) => h.pred !== h.label);
writeFileSync(join(ROOT, 'shared/ml/intent-nb.json'), JSON.stringify(finalNb));

const f = (x: number) => x.toFixed(3);
const md: string[] = ['# OCD-Eval results', '', '_Generated by `npm run eval`._', ''];
md.push(`Items: ${EVAL_SET.length} utterances in ${byLang.length} language groups.`, '');
md.push('## Overall', '', '| System | Accuracy | Macro-F1 | Self-harm recall | Panic recall |', '|---|---|---|---|---|');
systems.forEach((s) => md.push(`| ${s.name} | ${f(s.acc)} | ${f(s.macroF1)} | ${f(s.rep.SELF_HARM.recall)} | ${f(s.rep.PANIC.recall)} |`));
md.push('', `**Release gate** (hybrid self-harm recall >= ${GATE}): ${gatePassed ? 'PASSED' : 'FAILED'} (${f(selfHarmRecall)})`, '');
md.push('## Per-class (hybrid)', '', '| Intent | Precision | Recall | F1 | Support |', '|---|---|---|---|---|');
CLASSES.forEach((c) => {
  const r = hybrid.rep[c];
  md.push(`| ${c} | ${f(r.precision)} | ${f(r.recall)} | ${f(r.f1)} | ${r.support} |`);
});
md.push('', '## Confusion matrix (hybrid; rows = true, columns = predicted)', '', `| | ${CLASSES.join(' | ')} |`, `|---|${CLASSES.map(() => '---').join('|')}|`);
CLASSES.forEach((c, i) => md.push(`| ${c} | ${hybrid.cm[i].join(' | ')} |`));
md.push('', '## By language (hybrid accuracy)', '', '| Language | Items | Accuracy |', '|---|---|---|');
byLang.forEach((l) => md.push(`| ${l.lang} | ${l.n} | ${f(l.acc)} |`));
md.push('', '## Errors (hybrid)', '');
if (misses.length === 0) md.push('None.');
misses.forEach((m) => md.push(`- [${m.lang}] "${m.text}" - expected ${m.label}, got ${m.pred}`));
md.push('', '## Held-out set (never used for tuning)', '');
md.push(`Items: ${HOLDOUT_SET.length}. Accuracy ${f(hoAcc)}, macro-F1 ${f(macroF1(hoRep))}, self-harm recall ${f(hoRep.SELF_HARM.recall)}, panic recall ${f(hoRep.PANIC.recall)}.`, '');
md.push(`Self-harm items caught by the crisis screen OR the soft risk check-in: ${f(hoSafetyCatch)}.`, '');
md.push('**Finding (v1):** before the soft risk check-in existed, exact-phrase rules caught only 1 of 4 held-out self-harm phrasings (recall 0.25). Keyword rules do not generalise to new wording. The soft risk screen was added in response, so this held-out set is no longer fully unseen; a fresh held-out set (v2), clinician-labelled, is required. When a language model is connected, it acts as an additional safety classifier.', '', '**Update (v1.1):** explicit statements of suicidal thoughts ("thinking of taking my life", "no point living", "apne aap ko hurt karna hai") now open crisis support directly instead of only the soft check-in, and panic phrasing about breathing and heart rate was added. These additions were informed by held-out misses, so held-out numbers below are optimistic.', '');
md.push('This is the more honest estimate of real-world performance. Errors:', '');
if (hoMisses.length === 0) md.push('None.');
hoMisses.forEach((m) => md.push(`- [${m.lang}] "${m.text}" - expected ${m.label}, got ${m.pred}`));
md.push('', '## Limitations', '');
md.push('- The seed set was written by the project team; the rules were developed alongside it, so rule scores are optimistic. Model and hybrid scores use cross-validation.');
md.push('- Real-world speech-recognition errors and clinician labelling are needed before clinical use.');
md.push('- Tamil and Bengali coverage is small and needs native-speaker review.', '');
writeFileSync(join(ROOT, 'eval/RESULTS.md'), md.join('\n'));
writeFileSync(join(ROOT, 'shared/ml/eval-summary.json'), JSON.stringify({
  items: EVAL_SET.length,
  systems: systems.map((s) => ({ name: s.name, accuracy: Number(f(s.acc)), macroF1: Number(f(s.macroF1)), selfHarmRecall: Number(f(s.rep.SELF_HARM.recall)), panicRecall: Number(f(s.rep.PANIC.recall)) })),
  byLanguage: byLang.map((l) => ({ ...l, acc: Number(f(l.acc)) })),
  holdout: { items: HOLDOUT_SET.length, accuracy: Number(f(hoAcc)), selfHarmRecall: Number(f(hoRep.SELF_HARM.recall)), safetyCatch: Number(f(hoSafetyCatch)) },
  gate: { threshold: GATE, passed: gatePassed },
}, null, 2));

systems.forEach((s) => console.log(`${s.name.padEnd(30)} acc ${f(s.acc)}  macroF1 ${f(s.macroF1)}  self-harm recall ${f(s.rep.SELF_HARM.recall)}`));
byLang.forEach((l) => console.log(`  ${l.lang.padEnd(9)} n=${l.n} acc ${f(l.acc)}`));
console.log(`misses: ${misses.length}`);
misses.forEach((m) => console.log(`  - [${m.lang}] ${m.text} => ${m.pred} (expected ${m.label})`));
console.log(`Held-out: acc ${f(hoAcc)}  self-harm recall ${f(hoRep.SELF_HARM.recall)}  safety catch (crisis or check-in) ${f(hoSafetyCatch)}`);
hoMisses.forEach((m) => console.log(`  - [holdout ${m.lang}] ${m.text} => ${m.pred} (expected ${m.label})`));
console.log(`Release gate: ${gatePassed ? 'PASSED' : 'FAILED'}`);
process.exit(gatePassed ? 0 : 1);
